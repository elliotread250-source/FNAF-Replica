// Writes docs/MAP_INVENTORY.md: for every room, what is drawn there and how it collides. Generated from the same
// data the game runs on (layout, OFFICE_KIT, ROOM_KITS, the built level), so it can't drift from the code.
// npm run map:inventory
import { writeFileSync } from 'node:fs';
import { OFFICE_KIT, ROOM_KITS, getLevel, levelChecksum, propColliders } from '../shared/src';

const level = getLevel();
const out: string[] = [];
const f = (n: number) => n.toFixed(2).replace(/\.?0+$/, '');
out.push('# Map inventory: visual-to-collider, room by room');
out.push('');
out.push(`Generated by \`npm run map:inventory\` from the live level data (layout checksum \`${levelChecksum()}\`). Do not edit by hand.`);
out.push('');
out.push('Policies: **solid** blocks bodies with the listed boxes; **surface** rests on a solid part and has no collider of its own; **flat** is paper, paint, decals or cloth with no collider; **overhead** is above a jumping guard (lowest point at least 2.25 m over the floor). Doors block by their animated shape (`doorBoxes`).');
out.push('');
const totals = { solid: 0, surface: 0, flat: 0, overhead: 0, props: 0, doors: 0 };
for (const r of level.rooms) {
  const [x1, z1, x2, z2] = r.rects[0];
  out.push(`## ${r.name} (\`${r.id}\`)`);
  out.push('');
  out.push(`Floor y ${f(r.floorY)}, ceiling ${f(r.ceilH)} m, style \`${r.style}\`, circuit \`${r.circuit}\`, rect ${r.rects.map((q) => q.join(',')).join(' + ')} (${x2 - x1} x ${z2 - z1} m first rect). Linked to: ${(level.links[r.id] ?? []).join(', ') || 'none'}.`);
  out.push('');
  out.push('| Id / label | Kind | Policy | Collider boxes (x1..x2, z1..z2, y1..y2) |');
  out.push('| --- | --- | --- | --- |');
  const inRoom = (x: number, z: number) => r.rects.some(([a, b, c, d]) => x >= a && x <= c && z >= b && z <= d);
  for (const d of level.doors) {
    const mx = d.axis === 'z' ? (d.from + d.to) / 2 : d.line;
    const mz = d.axis === 'z' ? d.line : (d.from + d.to) / 2;
    if (Math.abs(d.floorY - r.floorY) > 0.1) continue;
    const near = [0.5, -0.5].some((o) => (d.axis === 'z' ? inRoom(mx, mz + o) : inRoom(mx + o, mz)));
    if (!near) continue;
    totals.doors++;
    out.push(`| ${d.name} | door (${d.kind}${d.locked ? `, locked: ${d.locked}` : ''}) | solid (animated) | posed by \`doorBoxes\`; closed slab ${d.axis}=${f(d.line)}, ${f(d.from)}..${f(d.to)}, h ${f(d.height)} |`);
  }
  for (const p of level.props.filter((q) => q.room === r.id)) {
    totals.props++;
    const boxes = propColliders(p);
    const label = String(p.p?.label ?? p.type);
    out.push(`| ${label} | prop \`${p.type}\` | ${boxes.length ? 'solid' : 'flat'} | ${boxes.map((b) => `${f(b.x1)}..${f(b.x2)}, ${f(b.z1)}..${f(b.z2)}, ${f(b.y1)}..${f(b.y2)}`).join('; ') || 'none'} |`);
  }
  const kit = [...ROOM_KITS.filter((p) => p.room === r.id), ...(r.id === 'office' ? OFFICE_KIT : [])];
  for (const p of kit) {
    totals[p.policy]++;
    const boxes = 'boxes' in p && p.boxes ? p.boxes : [];
    out.push(`| \`${p.id}\` ${p.note} | ${p.kind} | ${p.policy} | ${boxes.map((b) => `${f(b.x1)}..${f(b.x2)}, ${f(b.z1)}..${f(b.z2)}, ${f(b.y1)}..${f(b.y2)}`).join('; ') || 'none'} |`);
  }
  for (const h of level.hidingSpots.filter((q) => q.room === r.id)) out.push(`| hiding spot: ${h.type} | hide | trigger | none (bodies inside a spot don't collide); exits ${h.exits.map((e) => `${f(e.x)},${f(e.z)}`).join(' / ')} |`);
  out.push('');
}
out.push('## Totals');
out.push('');
out.push(`${level.rooms.length} rooms, ${totals.doors} door listings (shared doors appear in both rooms), ${totals.props} layout props, kit parts: ${totals.solid} solid, ${totals.surface} surface, ${totals.flat} flat, ${totals.overhead} overhead. ${level.colliders.length} collider boxes in the built level.`);
out.push('');
writeFileSync('docs/MAP_INVENTORY.md', out.join('\n'));
console.log(`wrote docs/MAP_INVENTORY.md (${out.length} lines)`);
